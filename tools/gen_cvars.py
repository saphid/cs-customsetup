"""Generate web/cvars.js, the console-setting allowlist, from a CS2 convar dump.

usage: python3 tools/gen_cvars.py DumpSource2/convars.txt DUMP_COMMIT > web/cvars.js

Allowed: convars CS2 saves per user ("archive"), minus cheat, development-only, hidden,
server (sv_) and Steam Cloud (cl_cloud_) settings, plus a few display toggles
that are not archived. Each entry records its type and range so values can be
checked: b = boolean, n = number [min, max], s = text.
"""
import json, re, sys

EXTRA = ['cl_showfps', 'cl_draw_only_deathnotices']
EXCLUDE = re.compile(r'^(sv_|cl_cloud_|mm_|demo_|sfm_)')
# Archived but not a player setting on a shared PC: account identity, server
# password, file names, and device IDs that only mean something on one PC.
EXCLUDE_NAMES = {'name', 'password', 'bug_submitter_override', 'cl_quickinventory_filename',
                 'sound_device_override', 'voice_device_override'}
# Narrower ranges where the dump's full range has side effects at a station:
# cl_showfps 4 also logs to a file that reset does not track.
OVERRIDES = {'cl_showfps': ['n', 0.0, 3.0]}
LINE = re.compile(r'^(\S+) (.*?) \((?:min: (\S+?), )?(?:max: (\S+?), )?([^()]*)\)$')

path, commit = sys.argv[1], sys.argv[2]
entries = {}
for line in open(path, encoding='utf-8'):
    m = LINE.match(line.rstrip('\n'))
    if not m:
        continue
    name, default, lo, hi, flags = m.groups()
    flags = flags.split()
    wanted = ('archive' in flags or name in EXTRA) and not EXCLUDE.match(name) and name not in EXCLUDE_NAMES
    if not wanted or {'cheat', 'developmentonly', 'hidden'} & set(flags):
        continue
    if default in ('true', 'false'):
        entries[name] = ['b']
    elif re.fullmatch(r'-?\d+(\.\d+)?', default):
        entries[name] = ['n', float(lo) if lo else None, float(hi) if hi else None]
    else:
        entries[name] = ['s']
for name, spec in OVERRIDES.items():
    if name not in entries:
        sys.exit(f'override for {name} not in dump')
    entries[name] = spec
missing = [n for n in EXTRA if n not in entries]
if missing:
    sys.exit(f'not in dump: {missing}')
print(f'// Generated by tools/gen_cvars.py from SteamDatabase GameTracking-CS2 {commit}')
print('// DumpSource2/convars.txt. Do not edit; regenerate after a CS2 update.')
print('export const CVARS = ' + json.dumps(entries, separators=(',', ':')).replace('],"', '],\n"') + ';')
